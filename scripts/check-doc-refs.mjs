#!/usr/bin/env node
// Doc-reference checker. Fails when a tracked Markdown file (plus CLAUDE.md,
// .claude/skills/** and .claude/agents/**) points at a repo path that does not
// exist, or at a "§ section" heading that is not in the target file.
//
//   node scripts/check-doc-refs.mjs        check the repo
//
// Rules:
//   1. A `backticked` span or a markdown link target that LOOKS like a repo
//      path (contains "/" or ends in a known extension) must exist. Links
//      resolve from the file's folder; backticked paths from the file's
//      folder, then from the repo root.
//   2. A fenced code block is checked token by token, with the same test, for
//      plain path-shaped tokens only (no spaces, globs, regexes or flags).
//   3. `path` § "Heading" (or → "Heading") needs a heading in that file whose
//      text starts with the quoted words (case-insensitive).
//   Ignored: URLs, anchor-only links, globs (*), placeholders (<...>, {...},
//   $VAR), absolute and home paths, and the allowlist below. A trailing
//   #anchor, :line or :line-line is stripped before the lookup.
//
// The checks are exported as pure functions; the tests use synthetic texts.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const KNOWN_EXTENSIONS = [
	"md",
	"ts",
	"tsx",
	"js",
	"mjs",
	"cjs",
	"json",
	"yaml",
	"yml",
	"toml",
	"png",
	"txt",
	"html",
	"sh",
];

// Paths that are allowed not to exist (kept short; each with its reason).
// Entries are exact paths or regexes, matched on the repo-root-relative form.
export const ALLOWLIST = [
	// Local output, ignored by git (see .gitignore): absent on a fresh clone.
	/^\.(visual-checks|e2e-output|expo)(\/|$)/,
	/^docs\/mockups\/v3\/renders\/.+/,
	/^tmp\//,
	/^scratch\//,
	// Generated by `npx expo start` / `expo prebuild`; never tracked.
	/^(ios|android)(\/|$)/,
	"expo-env.d.ts",
	"tsconfig.tsbuildinfo",
	".env",
	// Placeholders in examples ("x.ts", "x.web.test.ts").
	/(^|\/)x(\.[a-z]+)*\.[a-z]+$/,
	// Files that live outside the repo, in node_modules or in a CI artifact.
	/^(expo\/bundledNativeModules\.json|react-navigation\/.*|google-services\.json|eas\.json|coverage\.json)$/,
	/^(index\.html|summary\.md|results\.json|log\.txt|diagnostics\.txt|Documents\/dev-state\.json)$/,
	// Early mockup sources: outside the repo (kept at git tag mockups-v1-v2).
	/^(HabitFlowV2\.dc\.html|habit-components\.js|hab-25-f3a\.png)$/,
	// Described as gone, in an ADR and in the migration notes.
	"src/app/index.tsx",
	"index.ts",
	"meta/_journal.json",
	// Names of code and tests that were removed; the text says so.
	/^(DatabaseProvider\.web\.tsx|weekly-summary-helpers\.ts|habit-service\.test\.ts)$/,
	/^composite\/(column-bars|freeze-pool-card)\.tsx$/,
	/^(use-monthly-summary-queries\.test\.tsx|monthly-summary-helpers\.test\.ts|monthly-summary-screen\.test\.tsx)$/,
];

// Historical documents (audits, assessments) are not scanned: their paths
// describe the code as it was, and stale ones are expected there.
export const SKIP_PREFIXES = ["docs/archive/"];

// Instruction files an agent follows literally: a short path is a stale path.
// Elsewhere a path may be written relative to a module ("screens/x.tsx") as
// long as exactly one place in the repo ends with it.
export const STRICT = /^(CLAUDE\.md|AGENTS\.md|\.claude\/)/;

const EXT_RE = new RegExp(`\\.(${KNOWN_EXTENSIONS.join("|")})$`);

export function normalizeRef(raw) {
	let s = raw.trim();
	if (!s || /\s/.test(s)) return null;
	if (/:\/\//.test(s) || s.startsWith("mailto:")) return null;
	if (s.startsWith("#")) return null;
	if (/[*<>{}$|^()[\]"'=,;!?\\`…]/.test(s)) return null;
	if (/^[/~@-]/.test(s)) return null;
	s = s.replace(/#.*$/, "").replace(/:\d+(-\d+)?$/, "");
	if (s.endsWith("/")) s = s.slice(0, -1);
	if (!s) return null;
	if (!(s.includes("/") || EXT_RE.test(s))) return null;
	// "a/b" fragments with no dot and no known folder shape are still checked;
	// version strings and ratios like "1.5/2" are not paths.
	if (/^[\d.]+(\/[\d.]+)*$/.test(s)) return null;
	return s;
}

export function extractRefs(text) {
	const out = [];
	const lineAt = (i) => text.slice(0, i).split("\n").length;
	// Blank out fenced blocks for the inline scan, collect their tokens apart.
	const fenceRe = /^( {0,3})(```|~~~)[^\n]*\n([\s\S]*?)^\1\2[ \t]*$/gm;
	let inline = text;
	for (const m of text.matchAll(fenceRe)) {
		const bodyStart = m.index + m[0].indexOf("\n") + 1;
		let offset = bodyStart;
		for (const lineText of m[3].split("\n")) {
			let pos = 0;
			for (const tok of lineText.split(/(\s+)/)) {
				const ref = normalizeRef(tok);
				if (ref) {
					out.push({
						ref,
						kind: "fence",
						line: lineAt(offset + pos),
						end: offset + pos + tok.length,
					});
				}
				pos += tok.length;
			}
			offset += lineText.length + 1;
		}
		inline =
			inline.slice(0, m.index) +
			m[0].replace(/[^\n]/g, " ") +
			inline.slice(m.index + m[0].length);
	}
	for (const m of inline.matchAll(/\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
		const ref = normalizeRef(m[1]);
		if (ref) {
			out.push({
				ref,
				kind: "link",
				line: lineAt(m.index),
				end: m.index + m[0].length,
			});
		}
	}
	for (const m of inline.matchAll(/`([^`\n]+)`/g)) {
		const ref = normalizeRef(m[1]);
		if (ref) {
			out.push({
				ref,
				kind: "code",
				line: lineAt(m.index),
				end: m.index + m[0].length,
			});
		}
	}
	return out;
}

export function sectionAfter(text, end) {
	const m = /^\)?\s*(?:§|→)\s*["“]([^"”\n]+)["”]/.exec(
		text.slice(end, end + 200),
	);
	return m ? m[1].trim() : null;
}

function headingText(line) {
	return line
		.replace(/^#{1,6}\s+/, "")
		.replace(/[`*_]/g, "")
		.trim()
		.toLowerCase();
}

export function hasHeading(text, wanted) {
	const w = wanted.replace(/[`*_]/g, "").trim().toLowerCase();
	return text
		.split("\n")
		.filter((l) => /^#{1,6}\s/.test(l))
		.some((l) => headingText(l).startsWith(w));
}

function allowed(rel) {
	return ALLOWLIST.some((a) =>
		typeof a === "string" ? a === rel : a.test(rel),
	);
}

export function checkFile(file, text, fsApi) {
	const problems = [];
	const dir = path.posix.dirname(file);
	for (const { ref, kind, line, end } of extractRefs(text)) {
		const fromDir = path.posix.normalize(path.posix.join(dir, ref));
		const fromRoot = path.posix.normalize(ref);
		const candidates = kind === "link" ? [fromDir] : [fromDir, fromRoot];
		if (allowed(ref) || candidates.some(allowed)) continue;
		const found = candidates.find((c) => fsApi.exists(c));
		if (!found && kind !== "link") {
			if (!ref.includes("/")) {
				// A bare file name ("types.ts", "design-system.md"): it only has
				// to exist somewhere in the repo.
				if (ref.startsWith(".") || fsApi.baseNames.has(ref)) continue;
			} else if (!EXT_RE.test(ref) && !fsApi.topLevel.has(ref.split("/")[0])) {
				// "week/day", "chore/docs-set": prose, not a repo path.
				continue;
			}
		}
		if (
			!found &&
			kind !== "link" &&
			!STRICT.test(file) &&
			!fsApi.topLevel.has(ref.split("/")[0]) &&
			fsApi.endsWith(ref)
		) {
			continue; // module-relative path, resolves under src/
		}
		if (!found) {
			problems.push(`${file}:${line}: missing path "${ref}"`);
			continue;
		}
		const wanted = sectionAfter(text, end);
		if (wanted && /\.md$/.test(found)) {
			const target = fsApi.read(found);
			if (target !== null && !hasHeading(target, wanted)) {
				problems.push(
					`${file}:${line}: "${ref}" has no heading starting "${wanted}"`,
				);
			}
		}
	}
	return problems;
}

export function filesToScan(root) {
	const tracked = execFileSync("git", ["ls-files", "-z"], {
		cwd: root,
		encoding: "utf8",
		maxBuffer: 64 * 1024 * 1024,
	})
		.split("\0")
		.filter(Boolean);
	const set = new Set(
		tracked.filter(
			(f) =>
				/\.md$/.test(f) ||
				f === "CLAUDE.md" ||
				/^\.claude\/(skills|agents)\//.test(f),
		),
	);
	return {
		scan: [...set].filter(
			(f) =>
				!SKIP_PREFIXES.some((p) => f.startsWith(p)) &&
				fs.existsSync(path.join(root, f)),
		),
		tracked,
		topLevel: new Set(tracked.map((f) => f.split("/")[0])),
		baseNames: new Set(tracked.map((f) => f.split("/").pop())),
	};
}

export function run(root) {
	const { scan, tracked, topLevel, baseNames } = filesToScan(root);
	const fsApi = {
		topLevel,
		baseNames,
		endsWith: (ref) => tracked.some((f) => f.endsWith(`/${ref}`)),
		exists: (rel) => fs.existsSync(path.join(root, rel)),
		read: (rel) => {
			try {
				return fs.readFileSync(path.join(root, rel), "utf8");
			} catch {
				return null;
			}
		},
	};
	const problems = [];
	for (const f of scan) {
		problems.push(
			...checkFile(f, fs.readFileSync(path.join(root, f), "utf8"), fsApi),
		);
	}
	return problems;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
	const problems = run(root);
	if (problems.length > 0) {
		console.error("check-doc-refs: FAILED (stale doc references)");
		for (const p of problems) console.error(`  ${p}`);
		process.exit(1);
	}
	console.log("check-doc-refs: ok");
}
