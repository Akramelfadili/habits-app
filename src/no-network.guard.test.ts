/// <reference types="node" />
import fs from "node:fs";
import path from "node:path";

/**
 * E-02 / E-05: the "Data Not Collected" promise, kept by a test. Nothing in
 * `src/` talks to a network, and `package.json` carries no analytics or
 * crash-reporting package. Adding either means changing the privacy policy,
 * the App Privacy label (docs/how-to/app-store-privacy.md) and ADR 008 first;
 * then, and only then, this test.
 */

const ROOT = path.resolve(__dirname, "..");
const SRC = __dirname;

/** Network calls and web addresses. */
const FORBIDDEN: [string, RegExp][] = [
	["fetch(", /\bfetch\s*\(/],
	["XMLHttpRequest", /XMLHttpRequest/],
	["WebSocket", /WebSocket/],
	["axios", /axios/i],
	["an http(s):// string", /https?:\/\//],
];

/** The only places a web address may appear, with the reason. */
const ALLOWED: Record<string, string> = {
	"src/modules/habits/constants.ts":
		"PRIVACY_POLICY_URL: the hosted policy the About row opens in the browser",
	"src/lib/db/migrations/migrations.js":
		"a comment linking the drizzle docs, generated by drizzle-kit",
};

/** Packages that would send data off the device. */
const DENIED_PACKAGES =
	/^(@sentry\/|sentry-|firebase|@firebase\/|@react-native-firebase\/|react-native-firebase|expo-firebase|@segment\/|analytics-|react-native-analytics|amplitude|@amplitude\/|mixpanel|posthog|@datadog\/|@bugsnag\/|bugsnag|@react-native-community\/netinfo|appcenter|react-native-appsflyer|@statsig\/|@vercel\/analytics|rudder|@rudderstack\/|expo-updates|axios$)/;

function sourceFiles(dir: string): string[] {
	return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) return sourceFiles(full);
		return /\.(ts|tsx|js|jsx|mjs)$/.test(entry.name) ? [full] : [];
	});
}

describe("no network in src (E-02)", () => {
	const files = sourceFiles(SRC).filter((file) => file !== __filename);

	it("finds the source it is guarding", () => {
		expect(files.length).toBeGreaterThan(100);
	});

	it("no file calls the network or holds a web address, except the allowlist", () => {
		const hits: string[] = [];
		for (const file of files) {
			const relative = path.relative(ROOT, file).split(path.sep).join("/");
			const text = fs.readFileSync(file, "utf8");
			for (const [label, pattern] of FORBIDDEN) {
				if (!pattern.test(text)) continue;
				if (label === "an http(s):// string" && relative in ALLOWED) continue;
				hits.push(`${relative}: ${label}`);
			}
		}
		expect(hits).toEqual([]);
	});

	it("every allowlisted file still holds a web address (no stale entry)", () => {
		for (const relative of Object.keys(ALLOWED)) {
			const text = fs.readFileSync(path.join(ROOT, relative), "utf8");
			expect(text).toMatch(/https?:\/\//);
		}
	});

	it("the policy URL constant is the only app address", () => {
		const text = fs.readFileSync(
			path.join(ROOT, "src/modules/habits/constants.ts"),
			"utf8",
		);
		expect(text.match(/https?:\/\/[^"'`\s]+/g)).toEqual([
			"https://akramelfadili.github.io/habits-app/privacy.html",
		]);
	});
});

describe("no analytics or crash reporting in package.json (E-02)", () => {
	const manifest = JSON.parse(
		fs.readFileSync(path.join(ROOT, "package.json"), "utf8"),
	) as Record<string, Record<string, string> | undefined>;
	const names = [
		"dependencies",
		"devDependencies",
		"optionalDependencies",
		"peerDependencies",
	].flatMap((group) => Object.keys(manifest[group] ?? {}));

	it("lists no denied package", () => {
		expect(names.filter((name) => DENIED_PACKAGES.test(name))).toEqual([]);
	});

	it("the deny list recognises the usual suspects", () => {
		for (const name of [
			"@sentry/react-native",
			"firebase",
			"@react-native-firebase/analytics",
			"posthog-react-native",
			"@amplitude/analytics-react-native",
			"mixpanel-react-native",
			"@bugsnag/expo",
			"axios",
			"expo-updates",
		]) {
			expect(DENIED_PACKAGES.test(name)).toBe(true);
		}
	});
});
